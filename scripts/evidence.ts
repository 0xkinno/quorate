/** Writes EVIDENCE.md from docs/live-runs/*.json and docs/FACTS.json. Usage: npx tsx scripts/evidence.ts */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const usd = (c: number) => `$${(c / 100).toFixed(2)}`;
const facts = JSON.parse(readFileSync("docs/FACTS.json", "utf8"));
const NAMES: Record<string, string> = { L1: "Clean close", L2: "Below the minimum", L3: "PayPal declines family 7", L4: "Sponsor covers the gap", L5: "PayPal refuses a capture, teacher cancels", L6: "Process dies after the 9th capture", L7: "One family pays cash (PayPal invoice)" };
const runs = readdirSync("docs/live-runs").filter((f) => f.endsWith(".json")).map((f) => JSON.parse(readFileSync(`docs/live-runs/${f}`, "utf8")))
  .sort((a, b) => a.pool.createdAt.localeCompare(b.pool.createdAt));

let md = `# Evidence

Every live run on the PayPal sandbox, 12 Nov 2026, generated by \`scripts/evidence.ts\` from
\`docs/live-runs/*.json\`. Each run is also on the deployed site at \`/proof/<pool>\` with its attempt log.

**Totals** (docs/FACTS.json): ${facts.liveRuns.recorded} runs, ${facts.liveRuns.reachedTheClose} reached the close, ${facts.liveRuns.closedExact} exact to the cent,
${facts.liveRuns.closesSurvivingPayPalDecline} survived a PayPal-injected decline, ${facts.liveRuns.holdsPlaced} holds, ${facts.liveRuns.captures} captures, ${facts.liveRuns.refunds} refunds,
$${facts.liveRuns.dollarsSettled.toLocaleString("en-US", { minimumFractionDigits: 2 })} settled, ${facts.liveRuns.centsOff} cents off, ${facts.liveRuns.familiesAboveApprovedAmount} families above their approved amount.
Payouts: ${facts.liveRuns.payoutsSucceeded} SUCCESS, ${facts.liveRuns.payoutsDenied} DENIED. Tests: ${facts.tests.passed} of ${facts.tests.total}.

| Started (UTC) | Pool | Scenario | Holds | State | Charged | Vendors due | Payout batch |
|---|---|---|---|---|---|---|---|
`;
for (const r of runs) {
  const sc = r.scenario ?? (r.pool.decline ? "L3" : "L1");
  const rc = r.close?.reconciled;
  md += `| ${r.pool.createdAt.slice(11, 19)} | \`${r.pool.id}\` | ${sc} ${NAMES[sc] ?? ""} | ${r.members.filter((m: { authId?: string }) => m.authId).length} | ${r.pool.state} | ${rc ? usd(rc.netCharged) : "-"} | ${rc ? usd(rc.vendorsDue) : "-"} | ${r.close?.payout?.batchId ? `\`${r.close.payout.batchId}\` ${r.close.payout.status}` : "-"} |\n`;
}
md += `\n## Notes on each kind of run\n`;
for (const r of runs) {
  const sc = r.scenario ?? (r.pool.decline ? "L3" : "L1");
  const steps: string[] = r.close?.steps ?? [];
  const decl = steps.filter((x) => /declined|refused|top-up|refunded|cash back|died/i.test(x)).slice(0, 4);
  md += `\n### ${r.pool.id}: ${NAMES[sc] ?? sc}\n`;
  if (r.pool.note) md += `${r.pool.note}\n\n`;
  if (decl.length) md += decl.map((x) => `- ${x}`).join("\n") + "\n";
  const sample = r.members.find((m: { authId?: string }) => m.authId && !String(m.authId).startsWith("CASH"));
  if (sample) md += `- Example authorization: \`${sample.authId}\` (order \`${sample.orderId}\`)\n`;
  const cap = r.close?.members?.find((m: { captures: unknown[] }) => m.captures.length);
  if (cap) md += `- Example capture: \`${cap.captures[0].captureId}\` ${usd(cap.captures[0].cents)}\n`;
}
md += `
## Failed runs, kept
- A run whose hold creation lost the network ("fetch failed") before any capture: no money moved. Network
  calls are now retried with the same PayPal-Request-Id.
- A run that charged every family exactly ($1,592.00 after PayPal's decline) and then had its payout refused
  with INSUFFICIENT_FUNDS while new funds were held; the old code stopped there. Now the charges stand and the
  payout is retried with a new sender_batch_id.
- The first clean close's payout was DENIED (RECEIVER_COUNTRY_NOT_ALLOWED): its vendor accounts were outside a
  payout country. Later runs pay US vendor accounts and reach SUCCESS.

## Other evidence
- Probe answers P1 to P10 with debug ids: FINDINGS.md, raw files in docs/probe/.
- The crew, live on Gemini: docs/crew-run.json.
- Counterfactual (a seeded model, not a measurement): docs/counterfactual.json.
`;
writeFileSync("EVIDENCE.md", md);
console.log(md.split("\n").slice(0, 26).join("\n"));
