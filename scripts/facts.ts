/**
 * docs/FACTS.json: every headline number, generated from recorded files. Never typed by hand.
 * Sources: docs/live-runs/*.json (live sandbox runs), docs/probe/*.json (platform probe),
 * docs/counterfactual.json, and the test suite (vitest JSON reporter).
 * Usage: npx tsx scripts/facts.ts          writes docs/FACTS.json
 *        npx tsx scripts/facts.ts --check  fails if FACTS.json differs from what the files say (CI)
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { execSync } from "node:child_process";

type Run = { scenario?: string; pool: { id: string; title: string; port: string; state: string; decline?: string; createdAt: string; holdSource: string };
  members: { authId?: string }[]; close?: { state?: string; reconciled?: { vendorsDue: number; netCharged: number; exact: boolean }; payout?: { batchId: string; status: string }; members?: { chargedCents: number; capCents: number; captures: unknown[]; refunds: unknown[] }[] }; seconds?: number };

const runs: Run[] = readdirSync("docs/live-runs").filter((f) => f.endsWith(".json")).map((f) => JSON.parse(readFileSync(`docs/live-runs/${f}`, "utf8")));
const sandbox = runs.filter((r) => r.pool.port === "sandbox");
const closed = sandbox.filter((r) => r.close?.reconciled);
const paidOut = closed.filter((r) => r.close?.payout?.batchId);
const holds = sandbox.reduce((s, r) => s + r.members.filter((m) => m.authId && !m.authId.startsWith("CASH")).length, 0);
const captures = sandbox.reduce((s, r) => s + (r.close?.members ?? []).reduce((a, m) => a + m.captures.length, 0), 0);
const refunds = sandbox.reduce((s, r) => s + (r.close?.members ?? []).reduce((a, m) => a + m.refunds.length, 0), 0);
const aboveCap = sandbox.reduce((s, r) => s + (r.close?.members ?? []).filter((m) => m.chargedCents > m.capCents).length, 0);
const centsOff = closed.reduce((s, r) => s + Math.abs(r.close!.reconciled!.vendorsDue - r.close!.reconciled!.netCharged), 0);
const declineClosed = closed.filter((r) => r.pool.decline && r.close?.state === "CLOSED");

let tests = { total: 0, passed: 0 };
try {
  const j = JSON.parse(execSync("npx vitest run --reporter=json", { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }));
  tests = { total: j.numTotalTests, passed: j.numPassedTests };
} catch (e) { const out = (e as { stdout?: string }).stdout; if (out) { const j = JSON.parse(out); tests = { total: j.numTotalTests, passed: j.numPassedTests }; } }

const cf = existsSync("docs/counterfactual.json") ? JSON.parse(readFileSync("docs/counterfactual.json", "utf8")) : null;
const probes = readdirSync("docs/probe").filter((f) => f.endsWith(".json")).sort();

const facts = {
  source: "generated by scripts/facts.ts from docs/live-runs, docs/probe, docs/counterfactual.json and the test suite",
  liveRuns: {
    recorded: sandbox.length, closedExact: closed.filter((r) => r.close!.reconciled!.exact).length, withPayoutBatch: paidOut.length,
    closesSurvivingPayPalDecline: declineClosed.length, holdsPlaced: holds, captures, refunds, centsOff, familiesAboveApprovedAmount: aboveCap,
    dollarsSettled: closed.reduce((s, r) => s + r.close!.reconciled!.netCharged, 0) / 100,
    scenarios: sandbox.map((r) => ({ pool: r.pool.id, scenario: r.scenario ?? (r.pool.decline ? "L3" : "L1"), title: r.pool.title, state: r.close?.state ?? r.pool.state, exact: r.close?.reconciled?.exact ?? null, payoutBatch: r.close?.payout?.batchId ?? null, seconds: r.seconds ?? null })),
  },
  probe: { files: probes, overCaptureAcceptedByPayPal: { authorizedCents: 7200, capturedCents: 8000 }, holdValidityDays: 29, reauthorizeTooSoonIssue: "REAUTHORIZATION_TOO_SOON", declineCodeUsed: "PAYER_CANNOT_PAY" },
  tests,
  counterfactual: cf ? { label: cf.label, trips: cf.trips, teacherFrontedDollars: cf.teacherFronts.teacherFronted / 100, teacherUnrecoveredDollars: cf.teacherFronts.teacherUnrecovered / 100, potRefundsIssued: cf.potUpFront.refundsIssued, potFamiliesChargedForCancelledTrips: cf.potUpFront.familiesChargedForCancelledTrip, quorateTeacherFronted: 0, quorateRefundsIssued: cf.quorate.refundsIssued, quorateFamiliesAboveFinalShare: cf.quorate.familiesAboveFinalShare, invariantFailures: cf.invariantFailures } : null,
};

const text = JSON.stringify(facts, null, 2) + "\n";
if (process.argv.includes("--check")) {
  const now = existsSync("docs/FACTS.json") ? readFileSync("docs/FACTS.json", "utf8") : "";
  if (now !== text) { console.error("docs/FACTS.json drifted from its sources. Run: npx tsx scripts/facts.ts"); process.exit(1); }
  console.log("FACTS.json matches its sources");
} else { writeFileSync("docs/FACTS.json", text); console.log(text); }
